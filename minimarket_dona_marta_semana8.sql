SELECT ID_EMPLEADO AS IDENTIFICADOR,
       NOMBRES||' '||APELLIDO_PATERNO||NVL(' '||APELLIDO_MATERNO,'') AS NOMBRE_COMPLETO,
       SUELDO AS SALARIO,
       NVL(BONO_JEFATURA,0) AS BONIFICACION,
       (SUELDO + NVL(BONO_JEFATURA,0)) AS SALARIO_SIMULADO
FROM EMPLEADO
WHERE ACTIVO = 'S' AND BONO_JEFATURA IS NOT NULL
ORDER BY SALARIO_SIMULADO DESC, APELLIDO_PATERNO DESC;

SELECT ID_EMPLEADO AS EMPLEADO,
       SUELDO AS SUELDO,
       ROUND(SUELDO*0.08,2) AS POSIBLE_AUMENTO,
       ROUND(SUELDO*1.08,2) AS SALARIO_SIMULADO
FROM EMPLEADO
WHERE SUELDO BETWEEN 550000 AND 800000
ORDER BY SUELDO ASC;
