
CREATE TABLE AFP (
  ID_AFP NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  NOMBRE VARCHAR2(80) UNIQUE NOT NULL
);

CREATE TABLE SALUD (
  ID_SALUD NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  NOMBRE VARCHAR2(80) UNIQUE NOT NULL
);

CREATE TABLE EMPLEADO (
  ID_EMPLEADO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  RUN VARCHAR2(12) NOT NULL,
  DV CHAR(1) NOT NULL,
  NOMBRES VARCHAR2(80) NOT NULL,
  APELLIDO_PATERNO VARCHAR2(60) NOT NULL,
  APELLIDO_MATERNO VARCHAR2(60),
  ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
  SUELDO NUMBER(12,2) NOT NULL,
  BONO_JEFATURA NUMBER(12,2),
  CORREO VARCHAR2(120),
  ID_AFP NUMBER NOT NULL,
  ID_SALUD NUMBER NOT NULL,
  CONSTRAINT UQ_EMPLEADO_RUN UNIQUE (RUN, DV),
  CONSTRAINT UQ_EMPLEADO_CORREO UNIQUE (CORREO),
  CONSTRAINT FK_EMPLEADO_AFP FOREIGN KEY (ID_AFP) REFERENCES AFP(ID_AFP),
  CONSTRAINT FK_EMPLEADO_SALUD FOREIGN KEY (ID_SALUD) REFERENCES SALUD(ID_SALUD),
  CONSTRAINT CHK_EMPLEADO_DV CHECK (REGEXP_LIKE(DV, '^[0-9Kk]$')),
  CONSTRAINT CHK_EMPLEADO_ACTIVO CHECK (UPPER(ACTIVO) IN ('S','N')),
  CONSTRAINT CHK_EMPLEADO_SUELDO CHECK (SUELDO >= 450000)
);

CREATE TABLE VENDEDOR (
  ID_VENDEDOR NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ID_EMPLEADO NUMBER NOT NULL,
  CONSTRAINT UQ_VENDEDOR_EMPLEADO UNIQUE (ID_EMPLEADO),
  CONSTRAINT FK_VENDEDOR_EMPLEADO FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADO(ID_EMPLEADO)
);

CREATE TABLE MEDIO_PAGO (
  ID_MEDIO_PAGO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  NOMBRE VARCHAR2(40) UNIQUE NOT NULL
);

CREATE TABLE PRODUCTO (
  ID_PRODUCTO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  NOMBRE VARCHAR2(100) NOT NULL,
  PRECIO NUMBER(10,2) NOT NULL,
  STOCK NUMBER(10,0) NOT NULL,
  CONSTRAINT CHK_PRODUCTO_PRECIO CHECK (PRECIO > 0),
  CONSTRAINT CHK_PRODUCTO_STOCK CHECK (STOCK >= 0)
);

CREATE TABLE VENTA (
  ID_VENTA NUMBER PRIMARY KEY,
  FECHA_VENTA DATE NOT NULL,
  MONTO_TOTAL NUMBER(12,2) NOT NULL,
  ID_VENDEDOR NUMBER NOT NULL,
  ID_MEDIO_PAGO NUMBER NOT NULL,
  CONSTRAINT FK_VENTA_VENDEDOR FOREIGN KEY (ID_VENDEDOR) REFERENCES VENDEDOR(ID_VENDEDOR),
  CONSTRAINT FK_VENTA_MEDIO FOREIGN KEY (ID_MEDIO_PAGO) REFERENCES MEDIO_PAGO(ID_MEDIO_PAGO)
);

CREATE SEQUENCE SEQ_VENTA START WITH 100 INCREMENT BY 1;

CREATE TABLE DETALLE_VENTA (
  ID_VENTA NUMBER NOT NULL,
  ID_PRODUCTO NUMBER NOT NULL,
  CANTIDAD NUMBER(10,0) NOT NULL,
  PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
  SUBTOTAL NUMBER(12,2) NOT NULL,
  CONSTRAINT PK_DETALLE_VENTA PRIMARY KEY (ID_VENTA, ID_PRODUCTO),
  CONSTRAINT FK_DV_VENTA FOREIGN KEY (ID_VENTA) REFERENCES VENTA(ID_VENTA),
  CONSTRAINT FK_DV_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTO(ID_PRODUCTO),
  CONSTRAINT CHK_DV_CANTIDAD CHECK (CANTIDAD > 0),
  CONSTRAINT CHK_DV_PRECIO CHECK (PRECIO_UNITARIO > 0),
  CONSTRAINT CHK_DV_SUBTOTAL CHECK (SUBTOTAL = CANTIDAD * PRECIO_UNITARIO)
);

